import {
  accessSync, chmodSync, constants, mkdirSync, readdirSync, readFileSync, renameSync, writeFileSync,
} from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Installs the completed-job hook for one runner.
 *
 * The runner starts ACTIONS_RUNNER_HOOK_JOB_COMPLETED only through a path
 * ending in `.sh` (run with bash) or `.ps1`, so the hook needs a `.sh` file.
 * That file is a generated one-line launcher: it execs the runner's bundled
 * Node on the typed hook installed beside it, and holds no logic. The bundled
 * Node ships with the runner package, so the hook needs neither a PATH Node
 * nor the network.
 */

/** Repository source of the typed hook. */
export const JOB_COMPLETED_HOOK_SOURCE = 'ci/src/runnerHooks/jobCompleted.ts';
/** Oldest bundled Node major that runs TypeScript without flags. */
const MIN_NODE_MAJOR = 24;

export interface JobCompletedHookFiles {
  /** The path the listener's ACTIONS_RUNNER_HOOK_JOB_COMPLETED names. */
  readonly launcher: string;
  /** The typed hook; `.mts` makes it an ES module without a package.json beside it. */
  readonly script: string;
}

export function jobCompletedHookFiles(hookRoot: string): JobCompletedHookFiles {
  return { launcher: join(hookRoot, 'job-completed.sh'), script: join(hookRoot, 'job-completed.mts') };
}

/**
 * Returns the newest bundled Node under the runner's `externals`. The path
 * goes through the `externals` link a runner self-update repoints, so it
 * stays valid across updates that keep the same Node major.
 */
export function resolveRunnerNode(runnerRoot: string): string {
  const externals = join(runnerRoot, 'externals');
  let names: string[];
  try {
    names = readdirSync(externals);
  } catch (error) {
    throw new Error(`Cannot list the runner's bundled tools in ${externals}: ${String(error)}`);
  }
  const candidates = names
    .map((name) => ({ name, major: Number(/^node(\d+)$/.exec(name)?.[1] ?? Number.NaN) }))
    .filter(({ major }) => major >= MIN_NODE_MAJOR)
    .sort((left, right) => right.major - left.major);
  for (const { name } of candidates) {
    const node = join(externals, name, 'bin/node');
    try {
      accessSync(node, constants.X_OK);
      return node;
    } catch {
      continue;
    }
  }
  throw new Error(
    `No executable bundled Node ${MIN_NODE_MAJOR} or newer under ${externals}`
    + ` (found: ${names.join(', ') || 'nothing'}); update the runner package.`,
  );
}

function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

export function renderLauncher(node: string, script: string): string {
  return [
    '#!/usr/bin/env bash',
    `# Generated by ci/src/actions/installJobCompletedHook.ts; the hook logic is ${JOB_COMPLETED_HOOK_SOURCE}.`,
    '# The runner starts a job hook only through a .sh or .ps1 path, so this launcher hands off to the typed hook.',
    `exec ${shellQuote(node)} ${shellQuote(script)}`,
    '',
  ].join('\n');
}

function writeAtomically(path: string, content: string | Buffer, mode: number): void {
  const temporary = `${path}.install-${process.pid}`;
  writeFileSync(temporary, content, { mode });
  chmodSync(temporary, mode);
  renameSync(temporary, path);
}

/**
 * Installs the typed hook, then its launcher. Each file is replaced
 * atomically, and the launcher last, so a job completing mid-install runs
 * either the previous hook or the new one.
 */
export function installJobCompletedHook(options: {
  readonly repositoryRoot: string;
  readonly runnerRoot: string;
  readonly hookRoot: string;
}): JobCompletedHookFiles {
  const node = resolveRunnerNode(options.runnerRoot);
  const files = jobCompletedHookFiles(options.hookRoot);
  mkdirSync(options.hookRoot, { recursive: true, mode: 0o755 });
  writeAtomically(files.script, readFileSync(join(options.repositoryRoot, JOB_COMPLETED_HOOK_SOURCE)), 0o644);
  writeAtomically(files.launcher, renderLauncher(node, files.script), 0o755);
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [runnerRoot, hookRoot] = process.argv.slice(2);
  if (runnerRoot === undefined || hookRoot === undefined) {
    console.error('usage: installJobCompletedHook.ts RUNNER_ROOT HOOK_ROOT');
    process.exit(2);
  }
  const repositoryRoot = resolve(fileURLToPath(new URL('../../..', import.meta.url)));
  try {
    const files = installJobCompletedHook({ repositoryRoot, runnerRoot, hookRoot });
    console.log(`Installed ${files.launcher} and ${files.script}.`);
  } catch (error: unknown) {
    console.error(`::error::${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
