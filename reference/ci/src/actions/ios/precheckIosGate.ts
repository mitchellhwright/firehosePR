/**
 * The iOS change gate's precheck, as a typed program.
 *
 * It runs before anything is checked out, decides which iOS lanes an event
 * selects, and refuses any event whose identity it cannot re-verify against
 * the live pull request. Every decision lives in `ci/src/ios/iosGatePrecheck.ts`;
 * this file reads the environment, performs the GitHub reads and the local
 * git merge proof, and writes the step's outputs.
 */

const environmentSchema = z.object({
  EVENT_NAME: z.string().min(1, 'EVENT_NAME is required'),
  REPOSITORY: z.string().min(1, 'REPOSITORY is required'),
  GITHUB_API_URL: z.string().min(1, 'GITHUB_API_URL is required'),
  GITHUB_SHA: z.string().min(1, 'GITHUB_SHA is required'),
  GITHUB_WORKFLOW_REF: z.string().min(1, 'GITHUB_WORKFLOW_REF is required'),
  GITHUB_WORKFLOW_SHA: z.string().min(1, 'GITHUB_WORKFLOW_SHA is required'),
  BASE_BRANCH: z.string().default(''),
  BASE_SHA: z.string().default(''),
  HEAD_BRANCH: z.string().default(''),
  HEAD_SHA: z.string().default(''),
  HEAD_REPOSITORY: z.string().default(''),
  GITHUB_TOKEN: z.string().default(''),
  GITHUB_FALLBACK_TOKEN: z.string().default(''),
  PR_NUMBER: z.string().default(''),
  TEST_SCOPE: z.string().default(''),
  PROMOTION_BASE_SHA: z.string().default(''),
  GITHUB_REF: z.string().default(''),
  GITHUB_SERVER_URL: z.string().default(''),
  RUNNER_TEMP: z.string().default(''),
});
type GateEnvironment = z.infer<typeof environmentSchema>;

/** The event identity written to the step outputs, after any dispatch adoption. */
interface GateIdentity {
  readonly prNumber: string;
  readonly headSha: string;
  readonly baseSha: string;
  readonly baseBranch: string;
}

const askpassSource = `#!/usr/bin/env node
// Generated by ci/src/actions/ios/precheckIosGate.ts. Git asks for credentials
// on its own stdin; answering through this helper keeps the token out of the
// process arguments, where any user on the runner could read it.
const prompt = process.argv[2] ?? '';
if (prompt.includes('Username')) {
  process.stdout.write('x-access-token\\n');
} else if (prompt.includes('Password')) {
  const token = process.env.PROMOTION_GIT_TOKEN;
  if (token === undefined || token.length === 0) process.exit(1);
  process.stdout.write(token + '\\n');
} else {
  process.exit(1);
}
`;

function annotate(message: string): void {
  console.log(`::error::${message}`);
}

function failure(message: string): GateDecision {
  return { kind: 'error', message };
}

function success(gateOutcome: GateOutcome): GateDecision {
  return { kind: 'outcome', outcome: gateOutcome };
}

/**
 * Adapts the shared reader to the outcome shape the decision module consumes:
 * a transport failure is a distinct answer from any HTTP status, because the
 * gate must fail closed on "no answer" rather than treat it as a rejection.
 */
function readerFor(tokens: readonly string[]): (url: string) => Promise<GateApiOutcome> {
  const read: GithubReader = createGithubReader({ tokens });
  return async (url: string): Promise<GateApiOutcome> => {
    try {
      const response = await read(url);
      return { kind: 'response', statusLabel: response.statusLabel, body: response.body };
    } catch (error: unknown) {
      if (error instanceof GithubTransportError) return { kind: 'unreachable' };
      throw error;
    }
  };
}

/**
 * The bare repository, credential helper and git invocations the promotion
 * merge proof needs. Created only on the `main` path that reaches a chain
 * walk, so an ordinary pull request never pays for it.
 */
async function promotionChainReaders(
  environment: GateEnvironment,
  api: (url: string) => Promise<GateApiOutcome>,
  prNumber: string,
): Promise<PromotionChainReaders> {
  const runnerTemp = environment.RUNNER_TEMP;
  if (runnerTemp.length === 0) throw new Error('RUNNER_TEMP is required to verify a promotion update chain');
  const gitDir = `${runnerTemp}/promotion-merge-proof.git`;
  const askpassPath = `${runnerTemp}/promotion-merge-proof-askpass.mjs`;
  writeFileSync(askpassPath, askpassSource, 'utf8');
  chmodSync(askpassPath, 0o700);

  const init = await runCommand('git', ['init', '--bare', gitDir]);
  if (init.status !== 0) throw new Error(`Could not create the promotion merge proof repository: ${init.stderr.trim()}`);
  const serverUrl = environment.GITHUB_SERVER_URL.length > 0
    ? environment.GITHUB_SERVER_URL
    : 'https://github.com';
  const remote = await runCommand('git', [
    '-C', gitDir, 'remote', 'add', 'origin', `${serverUrl}/${environment.REPOSITORY}.git`,
  ]);
  if (remote.status !== 0) throw new Error(`Could not register the promotion merge proof remote: ${remote.stderr.trim()}`);

  // The credential that last fetched successfully is reused for merge-tree,
  // which may still need to lazily fetch a blob from the filtered clone.
  let proofToken = '';
  const gitEnvironment = (token: string): NodeJS.ProcessEnv => ({
    ...process.env,
    PROMOTION_GIT_TOKEN: token,
    GIT_ASKPASS: askpassPath,
    GIT_TERMINAL_PROMPT: '0',
  });

  const fetchProofObject = async (sha: string): Promise<boolean> => {
    const present = await runCommand('git', ['-C', gitDir, 'cat-file', '-e', `${sha}^{commit}`]);
    if (present.status === 0) return true;
    for (const token of [environment.GITHUB_TOKEN, environment.GITHUB_FALLBACK_TOKEN]) {
      if (token.length === 0) continue;
      const fetched = await runCommand(
        'git',
        ['-C', gitDir, 'fetch', '--quiet', '--no-tags', '--depth=2', '--filter=blob:none', 'origin', sha],
        { env: gitEnvironment(token) },
      );
      if (fetched.status === 0) {
        proofToken = token;
        return true;
      }
    }
    return false;
  };

  return {
    readCommit: (sha) => api(`${environment.GITHUB_API_URL}/repos/${environment.REPOSITORY}/commits/${sha}`),
    compare: (from, to) => api(`${environment.GITHUB_API_URL}/repos/${environment.REPOSITORY}/compare/${from}...${to}`),
    fetchObject: fetchProofObject,
    mergeTree: async (mergeBase, left, right) => {
      const merged = await runCommand(
        'git',
        ['-C', gitDir, 'merge-tree', '--write-tree', '--merge-base', mergeBase, left, right],
        { env: gitEnvironment(proofToken) },
      );
      return merged.status === 0 ? merged.stdout.trim() : null;
    },
    verifyVersionChange: async (source, commit, version) => {
      if (!await fetchProofObject(source) || !await fetchProofObject(commit)) return false;
      const changed = await runCommand('git', [
        '-C', gitDir, 'diff-tree', '--no-commit-id', '--name-only', '-r', source, commit,
      ], { env: gitEnvironment(proofToken) });
      if (changed.status !== 0 || changed.stdout.trim() !== marketingVersionProjectPath) return false;
      const [before, after] = await Promise.all([
        runCommand('git', ['-C', gitDir, 'show', `${source}:${marketingVersionProjectPath}`], { env: gitEnvironment(proofToken) }),
        runCommand('git', ['-C', gitDir, 'show', `${commit}:${marketingVersionProjectPath}`], { env: gitEnvironment(proofToken) }),
      ]);
      if (before.status !== 0 || after.status !== 0) return false;
      try { return rewriteMarketingVersion(before.stdout, version) === after.stdout; }
      catch { return false; }
    },
    verifyVersionAttestation: (source, commit, version) =>
      checkpointHasVersionAttestation(api, `${environment.GITHUB_API_URL}/repos/${environment.REPOSITORY}`, prNumber, source, commit, version),
    verifyBareCheckpointVersion: (source) =>
      verifyBareCheckpointVersion(api, `${environment.GITHUB_API_URL}/repos/${environment.REPOSITORY}`, prNumber, source),
  };
}

async function decideDispatch(
  environment: GateEnvironment,
  api: (url: string) => Promise<GateApiOutcome>,
  identity: GateIdentity,
): Promise<{ readonly decision: GateDecision; readonly identity: GateIdentity }> {
  let resolved = identity;
  if (environment.TEST_SCOPE === 'promotion-evidence') {
    if (environment.GITHUB_REF !== 'refs/heads/develop'
      || !/^[0-9a-f]{40}$/u.test(environment.PROMOTION_BASE_SHA)
      || environment.PR_NUMBER !== '') {
      return {
        decision: failure('Promotion evidence requires develop, an exact main base SHA, and no PR-head dispatch.'),
        identity: resolved,
      };
    }
    const refs: Record<'develop' | 'main', string | undefined> = { develop: undefined, main: undefined };
    for (const branch of ['develop', 'main'] as const) {
      const response = await api(`${environment.GITHUB_API_URL}/repos/${environment.REPOSITORY}/git/ref/heads/${branch}`);
      const parsed = response.kind === 'response' && response.statusLabel === '200'
        ? z.object({ object: z.object({ sha: z.string() }) }).safeParse(response.body) : undefined;
      refs[branch] = parsed?.success ? parsed.data.object.sha : undefined;
    }
    if (!verifiedPromotionDispatchEndpoints({
      ref: environment.GITHUB_REF, sourceSha: environment.GITHUB_SHA,
      baseSha: environment.PROMOTION_BASE_SHA, prNumber: environment.PR_NUMBER,
      liveDevelopSha: refs.develop, liveMainSha: refs.main,
    })) {
      return {
        decision: failure('Promotion evidence develop/main ref moved or could not be verified at the exact source/base SHA.'),
        identity: resolved,
      };
    }
    resolved = {
      prNumber: '', headSha: environment.GITHUB_SHA,
      baseSha: environment.PROMOTION_BASE_SHA, baseBranch: 'main',
    };
    return { decision: manualDispatchDecision(environment.TEST_SCOPE, ''), identity: resolved };
  }
  if (resolved.prNumber.length > 0) {
    if (!isPositiveInteger(resolved.prNumber)) {
      return { decision: failure('pull_request_number must be a positive integer.'), identity: resolved };
    }
    const url = `${environment.GITHUB_API_URL}/repos/${environment.REPOSITORY}/pulls/${resolved.prNumber}`;
    const response = await api(url);
    if (response.kind === 'unreachable') {
      return {
        decision: failure(`Could not capture pull request #${resolved.prNumber} for this dispatch.`),
        identity: resolved,
      };
    }
    if (response.statusLabel !== '200') {
      return {
        decision: failure(
          `Unexpected GitHub response while capturing pull request #${resolved.prNumber}: HTTP ${response.statusLabel}.`,
        ),
        identity: resolved,
      };
    }
    const verified = verifiedDispatchPullRequest(response.body, environment.REPOSITORY, environment.GITHUB_SHA);
    if (verified === null) {
      return {
        decision: failure('PR-backed dispatch must target the exact current head of an open same-repository PR.'),
        identity: resolved,
      };
    }
    resolved = {
      prNumber: resolved.prNumber,
      headSha: verified.headSha,
      baseSha: verified.baseSha,
      baseBranch: verified.baseBranch,
    };
  }
  return { decision: manualDispatchDecision(environment.TEST_SCOPE, resolved.prNumber), identity: resolved };
}

async function decidePullRequest(
  environment: GateEnvironment,
  api: (url: string) => Promise<GateApiOutcome>,
  identity: GateIdentity,
): Promise<GateDecision> {
  const url = `${environment.GITHUB_API_URL}/repos/${environment.REPOSITORY}/pulls/${identity.prNumber}`;
  const current = await api(url);
  if (current.kind === 'unreachable') {
    return failure(`Could not revalidate pull request #${identity.prNumber}.`);
  }
  if (current.statusLabel !== '200') {
    return failure(
      `Unexpected GitHub response while revalidating pull request #${identity.prNumber}: HTTP ${current.statusLabel}.`,
    );
  }
  if (!pullRequestStillMatchesEvent(current.body, {
    baseBranch: identity.baseBranch,
    baseSha: identity.baseSha,
    headBranch: environment.HEAD_BRANCH,
    headSha: identity.headSha,
    headRepository: environment.HEAD_REPOSITORY,
  })) {
    return failure(
      `Pull request #${identity.prNumber} head or base changed after this event; a current event must own its checks.`,
    );
  }

  if (identity.baseBranch !== 'main') return success(changedFileRoutingOutcome());

  const admission = promotionAdmission(current.body, environment.HEAD_REPOSITORY, environment.REPOSITORY);
  if (admission.kind !== 'continue') return admission;

  const checkpointSha = promotionCheckpointSha(environment.HEAD_BRANCH);
  if (checkpointSha === null) {
    return failure('main only accepts production promotion checkpoints from an exact promotion/develop-<sha> branch');
  }
  const ancestry = await api(
    `${environment.GITHUB_API_URL}/repos/${environment.REPOSITORY}/compare/${checkpointSha}...develop`,
  );
  if (ancestry.kind === 'unreachable') {
    return failure(`Could not verify that promotion checkpoint ${checkpointSha} comes from develop.`);
  }
  if (ancestry.statusLabel !== '200') {
    return failure(
      `Unexpected GitHub response while checking promotion checkpoint ancestry: HTTP ${ancestry.statusLabel}.`,
    );
  }
  if (!checkpointIsOnDevelop(ancestry.body, checkpointSha)) {
    return failure(`Promotion checkpoint ${checkpointSha} is not an ancestor of develop.`);
  }

  if (identity.headSha === checkpointSha) {
    if (!await verifyBareCheckpointVersion(api, `${environment.GITHUB_API_URL}/repos/${environment.REPOSITORY}`, identity.prNumber, checkpointSha)) {
      return failure(`Promotion checkpoint ${checkpointSha} lacks a trusted checkpoint App version attestation.`);
    }
  } else {
    const chain = await verifyPromotionUpdateChain(
      {
        headSha: identity.headSha,
        headBranch: environment.HEAD_BRANCH,
        baseSha: identity.baseSha,
        checkpointSha,
      },
      await promotionChainReaders(environment, api, identity.prNumber),
    );
    if (chain.kind === 'error') return failure(chain.message);
  }
  return success(productionPromotionOutcome());
}

/**
 * A merge queue candidate is gated like a pull request into develop, with
 * the candidate as the head under test and the queue base as the trusted
 * base. It carries no PR number in its identity: the live-tuple guards check
 * the queue ref instead of a PR head, which a candidate never equals.
 */
async function decideMergeGroup(
  environment: GateEnvironment,
  tokens: readonly string[],
): Promise<{ readonly decision: GateDecision; readonly identity: GateIdentity }> {
  const event = readMergeGroupEvent();
  if (event === undefined) throw new Error('merge_group precheck ran outside a merge_group event.');
  const identity: GateIdentity = {
    prNumber: '', headSha: event.headSha, baseSha: event.trustedBaseSha, baseBranch: event.baseBranch,
  };
  if (environment.BASE_SHA !== event.trustedBaseSha || environment.HEAD_SHA !== event.headSha
    || environment.HEAD_BRANCH !== event.queueRef || environment.BASE_BRANCH !== MERGE_QUEUE_BASE_BRANCH) {
    return { decision: failure('Precheck environment does not match the merge_group payload tuple.'), identity };
  }
  const verification = await verifyMergeGroupCandidate(
    event, environment.GITHUB_API_URL, createGithubReader({ tokens }),
  );
  if (verification.kind === 'rejected') {
    return { decision: failure(`Merge queue candidate rejected: ${verification.message}`), identity };
  }
  return { decision: success(changedFileRoutingOutcome()), identity };
}

function writeOutcome(
  gateOutcome: GateOutcome,
  identity: GateIdentity,
  headBranch: string,
  eventSha: string,
  testScope: string,
): void {
  const verifierSha = trustedVerifierRevision(gateOutcome, headBranch, identity.baseSha, eventSha, testScope);
  appendStepOutputs([
    ['should_run', gateOutcome.shouldRun],
    ['needs_checkout', String(gateOutcome.needsCheckout)],
    ['storekit_required', String(gateOutcome.storekitRequired)],
    ['onboarding_required', String(gateOutcome.onboardingRequired)],
    ['budget_required', String(gateOutcome.budgetRequired)],
    ['production_promotion', String(gateOutcome.productionPromotion)],
    ['evidence_required', String(gateOutcome.evidenceRequired)],
    ['chat_plaid_required', String(gateOutcome.chatPlaidRequired)],
    ['income_required', String(gateOutcome.incomeRequired)],
    ['pr_number', identity.prNumber],
    ['expected_head_sha', identity.headSha],
    ['expected_base_sha', identity.baseSha],
    ['expected_base_ref', identity.baseBranch],
    ['verifier_sha', verifierSha],
    ['checkpoint_sha', gateOutcome.productionPromotion ? promotionCheckpointSha(headBranch) ?? '' : ''],
  ]);
  appendMultilineStepOutput('summary', gateOutcome.summary, 'SUMMARY');
}

async function run(): Promise<void> {
  const environment = readStepEnvironment(environmentSchema);
  console.log(
    `::notice::Workflow source: ${environment.GITHUB_WORKFLOW_REF} at ${environment.GITHUB_WORKFLOW_SHA}; event commit: ${environment.GITHUB_SHA}`,
  );
  const identity: GateIdentity = {
    prNumber: environment.PR_NUMBER,
    headSha: environment.HEAD_SHA,
    baseSha: environment.BASE_SHA,
    baseBranch: environment.BASE_BRANCH,
  };

  const schemaScope = developmentSchemaScopeDecision(environment.TEST_SCOPE);
  if (schemaScope !== null) return apply(schemaScope, identity, environment);

  const tokens = credentialTokens(environment.GITHUB_TOKEN, environment.GITHUB_FALLBACK_TOKEN);
  if (environment.EVENT_NAME === 'merge_group') {
    const queued = await decideMergeGroup(environment, tokens);
    return apply(queued.decision, queued.identity, environment);
  }
  const api = readerFor(tokens);
  if (environment.EVENT_NAME !== 'pull_request') {
    const dispatch = await decideDispatch(environment, api, identity);
    return apply(dispatch.decision, dispatch.identity, environment);
  }
  return apply(await decidePullRequest(environment, api, identity), identity, environment);
}

function apply(decision: GateDecision, identity: GateIdentity, environment: GateEnvironment): void {
  if (decision.kind === 'error') {
    annotate(decision.message);
    process.exitCode = 1;
    return;
  }
  if (environment.EVENT_NAME === 'merge_group') {
    // The verifier every later job checks out must be the queue base, never the candidate.
    const verifierSha = trustedVerifierRevision(
      decision.outcome, environment.HEAD_BRANCH, identity.baseSha, environment.GITHUB_SHA,
    );
    if (verifierSha !== identity.baseSha || verifierSha === environment.GITHUB_SHA) {
      annotate(`merge_group verifier ${verifierSha} is not the queue base ${identity.baseSha}.`);
      process.exitCode = 1;
      return;
    }
  }
  writeOutcome(decision.outcome, identity, environment.HEAD_BRANCH, environment.GITHUB_SHA, environment.TEST_SCOPE);
}

run().catch((error: unknown) => {
  annotate(`Typed iOS gate precheck failed: ${error instanceof Error ? error.message : String(error)}`);
  process.exitCode = 1;
});
