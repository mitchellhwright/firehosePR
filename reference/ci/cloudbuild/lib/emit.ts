import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { dump } from 'js-yaml';
import { validateCloudBuild, type CloudBuild } from './types.ts';

export const cloudBuildPath = 'cloudbuild.yaml';
export interface CloudBuildTarget {
  readonly path: string;
  readonly source: string;
}

export const developCloudBuildTarget: CloudBuildTarget = {
  path: cloudBuildPath,
  source: 'ci/cloudbuild/develop.ts',
};

export function renderCloudBuild<Id extends string>(
  build: CloudBuild<Id>,
  comments?: Readonly<Partial<Record<Id, string>>>,
  target: CloudBuildTarget = developCloudBuildTarget,
): string {
  validateCloudBuild(build);
  const options = { noRefs: true, lineWidth: -1, forceQuotes: true, quotingType: "'" as const };
  const steps = build.steps
    .map(({ name, id, waitFor, ...rest }) => {
      // Name comes first because existing source-inspection contracts delimit steps by builder.
      const fields = { name, id, ...(waitFor === undefined ? {} : { waitFor }), ...rest };
      const source = Object.entries(fields)
        .map(([key, value]) => {
          if (
            key === 'waitFor' ||
            key === 'secretEnv' ||
            (key === 'args' && rest.entrypoint === 'npm')
          )
            return `${key}: ${dump(value, { ...options, flowLevel: 0 }).trim()}\n`;
          // Let the YAML emitter use literal blocks for unchanged multiline Bash bodies.
          const multilineArgs =
            key === 'args' &&
            Array.isArray(value) &&
            value.some((argument) => typeof argument === 'string' && argument.includes('\n'));
          return dump({ [key]: value }, { ...options, forceQuotes: !multilineArgs });
        })
        .join('');
      const comment = comments?.[id];
      return (
        (comment
          ? comment
              .split('\n')
              .map((line) => `  # ${line}\n`)
              .join('')
          : '') +
        source
          .split('\n')
          .slice(0, -1)
          .map((line, index) => (line === '' ? '' : `${index === 0 ? '  - ' : '    '}${line}`))
          .join('\n')
      );
    })
    .join('\n');
  const { steps: _steps, ...rest } = build;
  return (
    `# Generated by ci/scripts/cloudbuild.ts from ${target.source}. Do not edit.\n` +
    `steps:\n${steps}\n${dump(rest, options)}`
  );
}

export function cloudBuildInSync<Id extends string>(
  root: string,
  build: CloudBuild<Id>,
  comments?: Readonly<Partial<Record<Id, string>>>,
  target: CloudBuildTarget = developCloudBuildTarget,
): boolean {
  const path = join(root, target.path);
  return existsSync(path) && readFileSync(path, 'utf8') === renderCloudBuild(build, comments, target);
}

export function writeCloudBuild<Id extends string>(
  root: string,
  build: CloudBuild<Id>,
  comments?: Readonly<Partial<Record<Id, string>>>,
  target: CloudBuildTarget = developCloudBuildTarget,
): void {
  const path = join(root, target.path);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, renderCloudBuild(build, comments, target));
}
